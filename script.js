// ============================================
// STATE MANAGEMENT
// ============================================
let currentLang = localStorage.getItem('zodiac-lang') || 'en';
let currentTheme = localStorage.getItem('zodiac-theme') || 'light';
let currentFilter = localStorage.getItem('zodiac-filter') || 'all';
let searchQuery = '';

// ============================================
// INITIALIZATION
// ============================================
document.addEventListener('DOMContentLoaded', () => {
    initializeApp();
    loadSavedPreferences();
    renderZodiacCards();
    attachEventListeners();
});

function initializeApp() {
    // Apply saved theme
    document.body.setAttribute('data-theme', currentTheme);
    updateThemeIcon();
    
    // Apply saved language
    updateLanguage();
    
    // Apply saved filter
    document.getElementById('elementFilter').value = currentFilter;
}

function loadSavedPreferences() {
    // Load from localStorage
    const savedLang = localStorage.getItem('zodiac-lang');
    const savedTheme = localStorage.getItem('zodiac-theme');
    const savedFilter = localStorage.getItem('zodiac-filter');
    
    if (savedLang) currentLang = savedLang;
    if (savedTheme) currentTheme = savedTheme;
    if (savedFilter) currentFilter = savedFilter;
}

// ============================================
// RENDERING FUNCTIONS
// ============================================
function renderZodiacCards() {
    const grid = document.getElementById('zodiacGrid');
    const noResults = document.getElementById('noResults');
    
    // Filter zodiac data
    let filteredData = zodiacData;
    
    // Apply element filter
    if (currentFilter !== 'all') {
        filteredData = filteredData.filter(zodiac => zodiac.element === currentFilter);
    }
    
    // Apply search filter
    if (searchQuery) {
        filteredData = filteredData.filter(zodiac => {
            const searchLower = searchQuery.toLowerCase();
            return (
                zodiac.name.en.toLowerCase().includes(searchLower) ||
                zodiac.name.zh.includes(searchQuery) ||
                zodiac.element.toLowerCase().includes(searchLower)
            );
        });
    }
    
    // Clear grid
    grid.innerHTML = '';
    
    // Show/hide no results message
    if (filteredData.length === 0) {
        noResults.style.display = 'block';
        return;
    } else {
        noResults.style.display = 'none';
    }
    
    // Render cards
    filteredData.forEach(zodiac => {
        const card = createZodiacCard(zodiac);
        grid.appendChild(card);
    });
}

function createZodiacCard(zodiac) {
    const card = document.createElement('div');
    card.className = 'zodiac-card';
    card.setAttribute('data-tooltip', zodiac.tooltip[currentLang]);
    card.setAttribute('data-id', zodiac.id);
    
    card.innerHTML = `
        <div class="zodiac-icon">${zodiac.icon}</div>
        <h3 class="zodiac-name">${zodiac.name[currentLang]}</h3>
        <p class="zodiac-name-zh">${currentLang === 'en' ? zodiac.name.zh : zodiac.name.en}</p>
        <span class="zodiac-element element-${zodiac.element}">${getElementText(zodiac.element)}</span>
    `;
    
    card.addEventListener('click', () => openDetailPanel(zodiac));
    
    return card;
}

function getElementText(element) {
    const elementTranslations = {
        en: { Metal: 'Metal', Wood: 'Wood', Water: 'Water', Fire: 'Fire', Earth: 'Earth' },
        zh: { Metal: '金', Wood: '木', Water: '水', Fire: '火', Earth: '土' }
    };
    return elementTranslations[currentLang][element];
}

// ============================================
// DETAIL PANEL
// ============================================
function openDetailPanel(zodiac) {
    const panel = document.getElementById('detailPanel');
    const overlay = document.getElementById('overlay');
    
    // Populate panel content
    document.getElementById('detailIcon').textContent = zodiac.icon;
    document.getElementById('detailName').textContent = `${zodiac.name[currentLang]} (${zodiac.name[currentLang === 'en' ? 'zh' : 'en']})`;
    
    const elementSpan = document.getElementById('detailElement');
    elementSpan.textContent = getElementText(zodiac.element);
    elementSpan.className = `detail-element element-${zodiac.element}`;
    
    document.getElementById('detailDescription').textContent = zodiac.description[currentLang];
    
    // Populate traits
    const traitsList = document.getElementById('detailTraits');
    traitsList.innerHTML = '';
    zodiac.traits[currentLang].forEach(trait => {
        const li = document.createElement('li');
        li.textContent = trait;
        traitsList.appendChild(li);
    });
    
    // Show panel and overlay
    panel.classList.add('active');
    overlay.classList.add('active');
    
    // Prevent body scroll
    document.body.style.overflow = 'hidden';
}

function closeDetailPanel() {
    const panel = document.getElementById('detailPanel');
    const overlay = document.getElementById('overlay');
    
    panel.classList.remove('active');
    overlay.classList.remove('active');
    
    // Restore body scroll
    document.body.style.overflow = '';
}

// ============================================
// LANGUAGE TOGGLE
// ============================================
function toggleLanguage() {
    currentLang = currentLang === 'en' ? 'zh' : 'en';
    localStorage.setItem('zodiac-lang', currentLang);
    updateLanguage();
    renderZodiacCards();
}

function updateLanguage() {
    const langButton = document.getElementById('langToggle');
    langButton.querySelector('.lang-text').textContent = currentLang === 'en' ? '中文' : 'EN';
    
    // Update all elements with data-en and data-zh attributes
    document.querySelectorAll('[data-en]').forEach(element => {
        if (element.tagName === 'INPUT') {
            element.placeholder = element.getAttribute(`data-placeholder-${currentLang}`);
        } else if (element.tagName === 'OPTION') {
            element.textContent = element.getAttribute(`data-${currentLang}`);
        } else {
            element.textContent = element.getAttribute(`data-${currentLang}`);
        }
    });
}

// ============================================
// THEME TOGGLE
// ============================================
function toggleTheme() {
    currentTheme = currentTheme === 'light' ? 'dark' : 'light';
    document.body.setAttribute('data-theme', currentTheme);
    localStorage.setItem('zodiac-theme', currentTheme);
    updateThemeIcon();
}

function updateThemeIcon() {
    const themeButton = document.getElementById('themeToggle');
    const icon = themeButton.querySelector('.theme-icon');
    icon.textContent = currentTheme === 'light' ? '🌙' : '☀️';
}

// ============================================
// FILTERS & SEARCH
// ============================================
function handleFilterChange(event) {
    currentFilter = event.target.value;
    localStorage.setItem('zodiac-filter', currentFilter);
    renderZodiacCards();
}

function handleSearchInput(event) {
    searchQuery = event.target.value;
    renderZodiacCards();
}

// ============================================
// EVENT LISTENERS
// ============================================
function attachEventListeners() {
    // Theme toggle
    document.getElementById('themeToggle').addEventListener('click', toggleTheme);
    
    // Language toggle
    document.getElementById('langToggle').addEventListener('click', toggleLanguage);
    
    // Element filter
    document.getElementById('elementFilter').addEventListener('change', handleFilterChange);
    
    // Search input
    document.getElementById('searchInput').addEventListener('input', handleSearchInput);
    
    // Close panel
    document.getElementById('closePanel').addEventListener('click', closeDetailPanel);
    document.getElementById('overlay').addEventListener('click', closeDetailPanel);
    
    // Keyboard shortcuts
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') {
            closeDetailPanel();
        }
    });
}
